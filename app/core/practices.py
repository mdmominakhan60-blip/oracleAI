DEFAULT_DAYS = 21


def get(code: str) -> dict | None:
    item = PRACTICES.get(code)
    return {**item, "code": code} if item else None


def by_category() -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for code, item in PRACTICES.items():
        out.setdefault(item["category"], []).append({**item, "code": code})
    return out


def today_step(item: dict, day_index: int) -> str:
    """Что клиентка читает сегодня: этап программы под её день.

    Программа делится на этапы неравномерно (7+7+7, 10+15+15, по дню), поэтому
    считаем границы от длины программы, а не «по неделям».
    """
    program = item.get("program") or []
    if not program:
        return ""
    days = item.get("days") or DEFAULT_DAYS
    if len(program) == days:                     # по этапу на каждый день
        return program[min(max(day_index, 1), days) - 1]
    per_stage = max(1, days // len(program))
    stage = min(len(program) - 1, max(0, (max(day_index, 1) - 1) // per_stage))
    return program[stage]


def as_meta(item: dict) -> dict:
    """Всё, кроме описания, уезжает в meta_json — так практику правят в админке."""
    return {k: v for k, v in item.items()
            if k not in ("title", "about", "code")}

def _r(n: int) -> int:
    """Свести число к аркану 1..22."""
    while n > 22:
        n = sum(int(c) for c in str(n))
    return n if n > 0 else 22


def compute_matrix(birth_date: str) -> dict:
    d = datetime.strptime(birth_date, "%Y-%m-%d")
    a = _r(d.day)                       # личный аркан (характер)
    b = _r(d.month)                     # духовный аркан
    c = _r(sum(int(x) for x in str(d.year)))  # родовая линия (аркан рода)
    dd = _r(a + b + c)                  # линия предназначения (миссия)
    e = _r(a + b + c + dd)              # центр матрицы (зона комфорта)
    love = _r(a + dd)                   # линия любви (зеркально денежной: личность + миссия)
    money = _r(c + dd)                  # линия финансов

    def item(n, title):
        a_ = ARCANA[n]
        return {
            "n": n,
            "arcana": a_["name"],
            "title": title,
            "meaning": a_["meaning"],
            "keywords": a_["keywords"],
            "plus": a_["plus"],
            "minus": a_["minus"],
            "advice": a_["advice"],
        }

    return {
        "personal": item(a, "Личный аркан (характер)"),
        "spirit": item(b, "Духовный аркан"),
        "family": item(c, "Родовая линия"),
        "destiny": item(dd, "Линия предназначения"),
        "center": item(e, "Центр матрицы"),
        "love": item(love, "Линия любви"),
        "money": item(money, "Линия денег"),
    }


def matrix_brief(m: dict) -> str:
    """Краткая сводка Матрицы: данные + короткий смысл (плюс/минус).

    Даёт факты и опорные смыслы, а не глубокую трактовку — её делает LLM через guide.
    Формат читают системные промпты агентов и навык get_matrix.
    """
    return "; ".join(
        f"{v['title']}: {v['n']} {v['arcana']}"
        f" (плюс: {v['plus']} минус: {v['minus']})"
        for v in m.values()
    )
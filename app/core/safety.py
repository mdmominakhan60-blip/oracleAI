async def helplines(db=None) -> list[str]:
    if db is None:
        return list(DEFAULT_HELPLINES)
    try:
        from ..repo import content as content_repo
        value = await content_repo.get_setting(db, "safety.helplines", None)
    except Exception as e:  # noqa: BLE001
        log.warning("контакты помощи из БД недоступны: %s", e)
        return list(DEFAULT_HELPLINES)
    if isinstance(value, list) and value:
        return [str(v) for v in value]
    return list(DEFAULT_HELPLINES)


async def crisis_reply(db, user, category: str) -> str:
    """Ответ на кризисное сообщение. Собирается кодом — модель сюда не зовём."""
    name = (user["name"] if user else None) or "милая"
    body = CRISIS_TEXTS.get(category, CRISIS_TEXTS["suicide"]).format(name=name)
    lines = await helplines(db)
    return body + "\n\n" + "\n".join(f"• {line}" for line in lines) + CRISIS_TAIL


def soften_rule(category: str) -> str:
    """Добавка к системному промпту для «чувствительных, но не кризисных» тем."""
    return SOFTEN_RULES.get(category, "")


async def record(db, tg_id: int, category: str, action: str, excerpt: str) -> None:
    """Журнал срабатываний: без него нельзя ни настроить фильтр, ни доказать,
    что сервис отреагировал правильно."""
    try:
        from ..data.session import transaction, utcnow
        async with transaction(db):
            await db.execute(
                "INSERT INTO safety_events(tg_id, category, excerpt, action, "
                "created_at) VALUES(:tg_id, :category, :excerpt, :action, :created_at)",
                {"tg_id": tg_id, "category": category,
                 "excerpt": (excerpt or "")[:300], "action": action,
                 "created_at": utcnow()})
    except Exception as e:  # noqa: BLE001
        log.warning("событие безопасности не записано: %s", e)

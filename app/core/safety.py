"""Кризисный протокол: что делать, когда вопрос выходит за рамки эзотерики.

Сервис говорит о судьбе, и рано или поздно в него приходят с «не хочу жить»,
«он меня бьёт», «у меня нашли опухоль». Предсказание в такой момент — не просто
бестактность, а вред. Поэтому решение принимает КОД, а не модель: правила в
системном промпте модель может обойти, а этот фильтр — нет.

Три уровня реакции:

- `CRISIS` (жизнь и здоровье под угрозой, насилие) — до агента вопрос не доходит.
  Клиентка получает тёплый человеческий ответ и контакты помощи, лимит вопросов
  не тратится: брать деньги за такое обращение нельзя.
- `SOFTEN` (болезнь, диагноз, беременность, суд, крупные деньги) — ответ идёт как
  обычно, но в системный промпт добавляется предписание не предсказывать исход и
  посоветовать специалиста.
- `NONE` — обычный вопрос.

Детектор локальный и без модели: он должен срабатывать за микросекунды и
работать даже когда все LLM-провайдеры лежат. Цена ложного срабатывания
(лишняя поддержка) несопоставима с ценой пропуска.
"""
from __future__ import annotations

import logging
import re
import unicodedata

log = logging.getLogger("oracle.safety")

NONE = "none"
SOFTEN = "soften"
CRISIS = "crisis"

# ─────────────────────────────── словари ──────────────────────────────────────
# Формулировки, а не отдельные слова: «умереть» встречается в «умереть со смеху»,
# а «покончить с собой» — почти никогда в безобидном контексте.


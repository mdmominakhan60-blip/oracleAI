export type TranslationKey = keyof (typeof dictionary)['ru'];

export function translate(
  lang: Lang,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const raw: string = dictionary[lang][key] ?? dictionary[DEFAULT_LANG][key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

/** Проверка на этапе разработки: словари не разошлись. */
export function dictionaryParity(): TranslationKey[] {
  const ru = Object.keys(dictionary.ru) as TranslationKey[];
  const en = Object.keys(dictionary.en) as TranslationKey[];
  return ru.filter((key) => !en.includes(key));
}
